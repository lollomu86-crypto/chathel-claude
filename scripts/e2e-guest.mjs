// E2E ospite: percorso completo con i componenti client REALI nel Chromium headless, contro le API demo reali.
// Uso: node scripts/e2e-guest.mjs   (costruisce e avvia da solo il harness su una porta libera)
import { startE2eServer } from './e2e/serve.mjs';
import { launch, newCtx, shot, ready, enterAsGuest, check, summary, T, re } from './e2e/lib.mjs';

const srv = await startE2eServer(Number(process.env.PORT || 3201));
const browser = await launch();
const t = T('it');
const noise = (e) => !/Service Worker|status of 401|favicon/.test(e);
let exit = 0;
try {
  // ---------- A: Giulia ----------
  const A = await newCtx(browser, { base: srv.base });
  const a = await A.ctx.newPage();
  console.log('\n# Ingresso: QR + Google demo + onboarding');
  await a.goto('/h/demo?k=demo-qr-token'); await ready(a);
  check(await a.getByRole('button', { name: re(t('onboarding.google')) }).isVisible(), 'schermata iniziale con "Continua con Google"');
  await a.getByRole('button', { name: re(t('onboarding.google')) }).click();
  check(await a.getByText(t('onboarding.demoIdentity')).isVisible(), 'in demo l\'identita\' e\' dichiarata simulata');
  await a.getByRole('button', { name: /Giulia/ }).click();
  await a.locator('#nick').waitFor();
  const checks = () => a.locator('#ob-list, #ob-chat, #ob-dm').evaluateAll((els) => els.map((e) => ({ checked: e.checked, disabled: e.disabled })));
  let cs = await checks();
  check(cs.length === 3 && cs.every((c) => !c.checked), 'i tre consensi non sono precompilati');
  check(cs.every((c) => c.disabled), 'senza maggiore eta\' i consensi social sono bloccati');
  await a.locator('label.check', { hasText: /18/ }).locator('input').check();
  cs = await checks();
  check(cs.every((c) => !c.checked) && !cs[0].disabled && cs[1].disabled && cs[2].disabled, 'dopo la conferma di eta\' si sblocca solo l\'elenco; chat e privati aspettano l\'elenco; tutto resta spento');
  check(await a.locator('form button[type=submit]').isDisabled(), 'senza informativa il pulsante Entra e\' disattivato');
  await shot(a, 'g-01-onboarding');
  await a.locator('#ob-list').check();
  cs = await checks();
  check(!cs[1].disabled && !cs[2].disabled && !cs[1].checked && !cs[2].checked, 'spuntato l\'elenco, chat e privati si sbloccano ma restano spenti');
  await a.locator('#ob-chat').check(); await a.locator('#ob-dm').check();
  await a.locator('label.check input[required]').check();
  await a.locator('form button[type=submit]').click();
  await a.waitForURL(/\/stay/); await a.locator('main#main').waitFor();
  check(await a.getByRole('heading', { name: re(t('home.welcome', { name: 'Giulia' })) }).isVisible(), 'home con il nome');
  await shot(a, 'g-02-home');

  console.log('\n# Bonus QR e conteggio richieste (F-01)');
  const reqs = []; a.on('request', (r) => { if (r.url().includes('/api/')) reqs.push(new URL(r.url()).pathname); });
  await a.goto('/stay/bonus'); await ready(a);
  await a.locator('canvas[role=img]').waitFor();
  await a.waitForTimeout(3000);
  const qrCalls = reqs.filter((p) => p.endsWith('/bonus-qr')).length;
  check(qrCalls >= 1 && qrCalls <= 3, `bonus-qr richiesto ${qrCalls} volte in 3 s (atteso 1-3)`);
  await shot(a, 'g-03-bonus');

  console.log('\n# Eventi');
  await a.goto('/stay/events'); await ready(a);
  await a.getByRole('button', { name: re(t('events.rsvp')) }).first().click();
  await a.getByText(re(t('events.going'))).first().waitFor();
  check(true, 'adesione a un evento');
  await shot(a, 'g-04-events');

  console.log('\n# Prenotazione');
  await a.goto('/stay/book'); await ready(a);
  await a.getByRole('button', { name: re(t('common.tomorrow')) }).click();
  await a.getByRole('button', { name: /^10:00/ }).click();
  await shot(a, 'g-04b-book-confirm');
  await a.getByRole('button', { name: re(t('book.confirmButton')) }).click();
  await a.getByText(t('book.booked')).waitFor();
  check(true, 'prenotazione confermata');
  await a.getByRole('button', { name: re(t('book.cancel')) }).first().click();
  await a.locator('dialog[open]').waitFor();
  await a.locator('dialog[open]').getByRole('button', { name: re(t('book.cancel')) }).click();
  await a.getByText(t('book.noBookings')).waitFor();
  check(true, 'annullamento con dialogo di conferma');

  console.log('\n# Reception AI ed emergenza');
  await a.goto('/stay/reception'); await ready(a);
  await a.getByRole('button', { name: re(t('reception.quickBreakfast')) }).click();
  await a.locator('.bubble-ai').nth(1).waitFor();
  check(true, 'risposta dell\'assistente');
  await a.getByRole('button', { name: re(t('reception.talkToOperator')) }).click();
  await a.getByText(re(t('reception.waiting'))).waitFor();
  check(true, 'passaggio allo staff');
  const ta = a.locator('textarea');
  await ta.fill('C\'e\' un\'emergenza, un ospite sta male');
  await ta.press('Enter');
  await a.locator('.emergency').waitFor();
  check(await a.locator('a[href="tel:112"]').isVisible(), 'banner emergenza con tel:112');
  await shot(a, 'g-05-reception-emergency');
  check(A.errors.filter(noise).length === 0, 'nessun errore di console nel percorso A: ' + A.errors.filter(noise).join(' | '));

  console.log('\n# Profilo: lingua e tema');
  await a.goto('/stay/profile'); await ready(a);
  await a.getByRole('radio', { name: /English/ }).click();
  await a.getByRole('heading', { name: 'Profile' }).waitFor({ timeout: 10000 });
  check(await a.evaluate(() => document.documentElement.lang) === 'en', 'cambio lingua in inglese: la pagina si traduce subito');
  await a.getByRole('button', { name: 'Dark' }).click();
  await a.waitForFunction(() => document.documentElement.getAttribute('data-theme') === 'dark');
  check(true, 'tema scuro scelto dal profilo');
  await a.getByRole('radio', { name: /Italiano/ }).click();
  await a.getByRole('heading', { name: t('profile.title') }).waitFor();

  console.log('\n# Ospiti: due persone, chat comune, segnalazione, richiesta privata, coupon');
  const B = await newCtx(browser, { base: srv.base });
  const b = await B.ctx.newPage();
  await enterAsGuest(b, { who: 'Marco' });
  await a.goto('/stay/social?tab=chat'); await ready(a);
  check(await a.getByRole('tab', { name: re(t('social.tabs.chat')) }).getAttribute('aria-selected') === 'true', 'la scheda Chat si apre da ?tab=chat');
  check(await a.getByRole('button', { name: re(t('social.chat.rulesAccept')) }).count() === 0, 'regole gia\' accettate dal consenso iniziale: nessun muro');
  await a.locator('#pub').fill('Ciao a tutti, sono Giulia!');
  await a.locator('#pub').press('Enter');
  await a.locator('.bubble-me', { hasText: 'Ciao a tutti' }).waitFor();
  check(true, 'A scrive nella chat comune');
  await b.goto('/stay/social?tab=chat'); await ready(b);
  const bub = b.locator('.bubble-other', { hasText: 'Ciao a tutti' });
  await bub.waitFor();
  check(await bub.locator('.who').innerText() === 'Giulia', 'B vede la bolla di Giulia con il nome in evidenza');
  await shot(b, 'g-06-chat-b');
  await b.getByRole('button', { name: re(t('social.chat.moreAbout', { name: 'Giulia' })) }).click();
  await b.getByRole('menuitem', { name: re(t('social.chat.report')) }).click();
  await b.locator('#report-why').selectOption('spam');
  await b.getByRole('button', { name: re(t('social.chat.reportSend')) }).click();
  await b.getByText(t('social.chat.reportThanks')).waitFor();
  check(true, 'B segnala il messaggio (dialogo, motivo, conferma)');
  check(await b.locator('dialog[open]').count() === 0, 'il dialogo si chiude dopo l\'invio');

  await b.goto('/stay/social'); await ready(b);
  const row = b.locator('.person', { hasText: 'Giulia' });
  await row.waitFor();
  check(await row.locator('.flag').count() === 1, 'nell\'elenco la lingua ha bandiera e nome');
  await row.getByRole('button', { name: re(t('social.people.write')) }).click();
  await b.locator('textarea[id^=rq-]').fill('Ti va un caffe\' domani?');
  await b.getByRole('button', { name: re(t('social.people.sendRequest')) }).click();
  await b.getByText(t('social.people.requestSent')).waitFor();
  check(true, 'B invia una richiesta di chat privata');
  await shot(b, 'g-07-people-b');

  await a.goto('/stay'); await ready(a);
  await a.getByText(re(t('home.socialRequests', { n: 1 }))).waitFor({ timeout: 15000 });
  check(true, 'A vede sulla home la richiesta in arrivo');
  const tabLabel = await a.locator('nav.tabbar a[href="/stay/social"]').getAttribute('aria-label');
  check(/1/.test(tabLabel ?? ''), 'la barra in basso annuncia i non letti: ' + tabLabel);
  await shot(a, 'g-08-home-request');
  await a.goto('/stay/social?tab=private'); await ready(a);
  await a.getByRole('button', { name: re(t('social.private.accept')) }).click();
  await a.locator('a.thread-main', { hasText: 'Marco' }).click();
  await a.locator('#pm').waitFor();
  check(true, 'A accetta la richiesta e apre la conversazione');
  check(await a.locator('.bubble-other .who', { hasText: 'Marco' }).count() >= 1, 'la bolla dell\'altro ospite porta il suo nome');
  await a.locator('#pm').fill('Volentieri, alle 9!'); await a.locator('#pm').press('Enter');
  await a.locator('.bubble-me', { hasText: 'alle 9' }).waitFor();
  await a.getByRole('button', { name: re(t('social.thread.couponsTitle')) }).click();
  await a.getByRole('button', { name: t('social.coupon.kinds.coffee') }).click();
  await a.getByRole('button', { name: re(t('social.thread.couponSend')) }).click();
  await a.locator('.ticket-mine').waitFor();
  check(true, 'A invia un coupon');
  await shot(a, 'g-09-thread-a');

  await b.goto('/stay/social?tab=private'); await ready(b);
  const dot = await b.locator('.thread .dot').count();
  check(dot >= 1, 'B vede il puntino dei non letti nella conversazione');
  await shot(b, 'g-10-private-b');
  await b.locator('a.thread-main', { hasText: 'Giulia' }).click();
  await b.locator('.ticket-theirs').waitFor();
  check(true, 'B vede il coupon come tessera');
  const qrResp = b.waitForResponse((r) => r.url().includes('social-coupon-qr'));
  await b.getByRole('button', { name: re(t('social.coupon.show')) }).click();
  const qr = await (await qrResp).json();
  check(typeof qr.qr?.token === 'string' && qr.qr.token.startsWith('c.'), 'B apre il QR del coupon (token "c.")');
  await b.locator('dialog[open] canvas, canvas[role=img]').first().waitFor();
  await shot(b, 'g-11-coupon-qr');
  console.log('COUPON_TOKEN=' + qr.qr.token);
  check(B.errors.filter(noise).length === 0, 'nessun errore di console per B: ' + B.errors.filter(noise).join(' | '));
  check(A.errors.filter(noise).length === 0, 'nessun errore di console per A (totale): ' + A.errors.filter(noise).join(' | '));
  await A.ctx.close(); await B.ctx.close();
} catch (e) { console.error(e); exit = 1; }
exit = summary() || exit;
await browser.close(); await srv.close();
process.exit(exit);
